#!/usr/bin/env node
/**
 * Action System Rename — dry-run engine.
 * Usage: node scripts/wip/rename-action-system.mjs [--phase=a|b|ab]
 * @module scripts/wip/rename-action-system
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RULES_A, RULES_B } from './rename-action-rules.mjs';

const ROOT = resolve(fileURLToPath(import.meta.url), '../../..');
const SKIP = new Set(['.git', '.next', 'node_modules', '.ignore', 'coverage']);
const EXTS = new Set(['.mdx', '.ts', '.tsx', '.mjs', '.json', '.js', '.md']);

/** Skip scripts/wip/ (path-based) and *.metadata.json (autogenerated). */
const shouldSkip = (p) =>
  p.includes('scripts\\wip') ||
  p.includes('scripts/wip') ||
  p.endsWith('.metadata.json') ||
  p.includes('foundry\\packs') ||
  p.includes('foundry/packs');

/**
 * Recursively walk dir for files matching EXTS, skipping SKIP dirs.
 * @param {string} dir
 * @returns {Promise<string[]>}
 */
async function walk(dir) {
  /** @type {string[]} */ const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (!SKIP.has(e.name)) out.push(...(await walk(p)));
    } else if (!shouldSkip(p)) {
      const x = e.name.slice(e.name.lastIndexOf('.'));
      if (EXTS.has(x)) out.push(p);
    }
  }
  return out;
}

/**
 * Apply ordered rules to a single line. Non-exclusive — later rules can match earlier output.
 * @param {string} line
 * @param {typeof RULES} rules
 * @returns {{ changed: boolean, result: string, hits: string[] }}
 */
function applyRules(line, rules) {
  let cur = line;
  /** @type {string[]} */ const hits = [];
  for (const r of rules) {
    r.re.lastIndex = 0;
    const next = cur.replace(r.re, r.to);
    if (next !== cur) {
      hits.push(r.desc);
      cur = next;
    }
  }
  return { changed: hits.length > 0, result: cur, hits };
}

// ─── Phase selection ───
const live = process.argv.includes('--live');
const phaseArg = process.argv.find((a) => a.startsWith('--phase='));
const phase = phaseArg ? phaseArg.split('=')[1] : 'ab';
const rules = [];
if (phase.includes('a')) rules.push(...RULES_A);
if (phase.includes('b')) rules.push(...RULES_B);
console.log(
  `Mode: ${live ? 'LIVE' : 'DRY RUN'}  Phase: ${phase}  Rules: ${rules.length}`,
);

// ─── Main ───
const dirs = [
  'src/content',
  'scripts',
  'src/lib',
  'tests',
  'foundry',
  '.github',
];

/** @type {Array<{ file: string, line: number, old: string, rule: string }>} */
const changes = [];
let scanned = 0,
  changed = 0;

for (const d of dirs) {
  const files = await walk(join(ROOT, d)).catch(() => []);
  for (const fp of files) {
    scanned++;
    const lines = (await readFile(fp, 'utf-8')).split('\n');
    let hadChange = false;
    for (let i = 0; i < lines.length; i++) {
      const r = applyRules(lines[i], rules);
      if (r.changed) {
        hadChange = true;
        for (const h of r.hits)
          changes.push({
            file: relative(ROOT, fp),
            line: i + 1,
            old: lines[i].trim().slice(0, 100),
            rule: h,
          });
        lines[i] = r.result;
      }
    }
    if (hadChange) {
      changed++;
      if (live) await writeFile(fp, lines.join('\n'), 'utf-8');
    }
  }
}

// ─── Report ───
const report = { scanned, changed, totalChanges: changes.length, changes };
const rp = join(ROOT, '.ignore', 'reports', `action-dry-${Date.now()}.json`);
mkdirSync(join(ROOT, '.ignore', 'reports'), { recursive: true });
writeFileSync(rp, JSON.stringify(report, null, 2));

// Full text output to .ignore/action-refactor.txt
const lines = [];
lines.push(`Phase: ${phase}  Rules: ${rules.length}`);
lines.push(
  `Scanned: ${scanned}  Files changed: ${changed}  Total changes: ${changes.length}`,
);
lines.push(`Report: ${relative(ROOT, rp)}`);
lines.push('');
for (const c of changes) {
  lines.push(`${c.file}:${c.line} [${c.rule}]`);
  lines.push(`  ${c.old}`);
}
writeFileSync(
  join(ROOT, '.ignore', 'action-refactor.txt'),
  lines.join('\n'),
  'utf-8',
);

console.log(
  `Scanned: ${scanned}  Files changed: ${changed}  Total changes: ${changes.length}`,
);
console.log(`Report: ${relative(ROOT, rp)}`);
console.log(
  `Full output: ${relative(ROOT, join(ROOT, '.ignore', 'action-refactor.txt'))}`,
);
