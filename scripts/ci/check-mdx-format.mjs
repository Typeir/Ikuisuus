/**
 * MDX Format Check
 *
 * @fileoverview Scans MDX content files for format violations: naming conventions,
 * structural issues, broken component usage, image path errors, and content type
 * specific format rules (monster sheets, spells, heirlooms).
 *
 * Outputs JSON-structured results to stdout matching the composite health check schema.
 *
 * @module scripts/ci/check-mdx-format
 */

import { promises as fs } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '../..');

const CONTENT_DIR = path.join(ROOT, 'src', 'content', 'en');
const MDX_COMPONENTS_FILE = path.join(
  ROOT,
  'src',
  'lib',
  'components',
  'mdx',
  'mdxComponents.tsx',
);
const MDX_INDEX_FILE = path.join(
  ROOT,
  'src',
  'lib',
  'components',
  'mdx',
  'index.tsx',
);

/**
 * Known MDX component names registered in src/lib/components/mdx/index.tsx
 *
 * @type {Set<string>}
 */
const REGISTERED_COMPONENTS = new Set([
  'BlendedImage',
  'FlexRenderer',
  'MonsterTable',
  'HeirloomTable',
  'SpellTable',
  'TrinketTable',
  'HorizontalSplit',
  'FloatedContainer',
  'ClearFloats',
  'ParallaxBackdrop',
  'Image',
]);

/**
 * Load auto-generated component names from mdxComponents.tsx
 *
 * @returns {Promise<Set<string>>} Set of component names
 */
async function loadAutoGeneratedComponents() {
  const names = new Set();
  try {
    const content = await fs.readFile(MDX_COMPONENTS_FILE, 'utf-8');
    const matches = content.matchAll(/mdxComponents\["(\w+)"\]/g);
    for (const match of matches) {
      names.add(match[1]);
    }
  } catch {
    /* file not found — skip */
  }
  try {
    const index = await fs.readFile(MDX_INDEX_FILE, 'utf-8');
    const matches = index.matchAll(/^\s+(\w+)(?:\s*[:,]|\s*:\s)/gm);
    for (const match of matches) {
      if (match[1][0] === match[1][0].toUpperCase()) {
        names.add(match[1]);
      }
    }
  } catch {
    /* file not found — skip */
  }
  return names;
}

/**
 * @typedef {Object} FormatRule
 * @property {string} name - Rule identifier
 * @property {RegExp|Function} check - Regex or function check
 * @property {string} message - Violation description
 * @property {string} suggestion - Fix suggestion
 * @property {string} severity - critical or warning
 * @property {string[]} [appliesTo] - Content types this rule applies to (omit for all)
 */

/** @type {FormatRule[]} */
const RULES = [
  {
    name: 'non-kebab-filename',
    check: (_, rel) =>
      /[A-Z_]/.test(path.basename(rel).replace(/\.sheet\.mdx$|\.mdx$/, '')),
    message: 'Filename is not kebab-case',
    suggestion:
      'Rename to kebab-case: lowercase letters, numbers, and hyphens only',
    severity: 'critical',
  },
  {
    name: 'fullsize-image-path',
    check: /src=["']\/full-size\//,
    message: 'Image references /full-size/ path — use /library/ path instead',
    suggestion: 'Change src="/full-size/..." to src="/library/..."',
    severity: 'critical',
  },
  {
    name: 'raw-img-tag',
    check: /<img\s/,
    message: 'Raw <img> tag — use <Image> or <BlendedImage> component',
    suggestion: 'Replace <img> with the Image or BlendedImage MDX component',
    severity: 'critical',
  },
  {
    name: 'unregistered-component',
    check: '__dynamic__',
    message: 'Uses unregistered MDX component',
    suggestion:
      'Register the component in src/lib/components/mdx/index.tsx or use a registered component',
    severity: 'critical',
  },
  {
    name: 'missing-h1',
    check: (content, rel) =>
      !path.basename(rel).startsWith('main') && !content.match(/^#\s+.+/m),
    message: 'Missing top-level heading (# Title)',
    suggestion: 'Add a # heading as the first line of the file',
    severity: 'warning',
  },
  {
    name: 'multiple-h1',
    check: (content) => {
      const h1s = content.match(/^#\s+.+/gm);
      return h1s && h1s.length > 1;
    },
    message: 'Multiple # headings — only one H1 per file',
    suggestion: 'Use ## or lower for subsequent sections',
    severity: 'warning',
    appliesTo: ['spells', 'world', 'items'],
  },
  {
    name: 'color-literal-in-mdx',
    check: /style=["'][^"']*#[0-9a-fA-F]{3,8}/,
    message: 'Inline color literal in style attribute',
    suggestion:
      'Use CSS variables via className instead of inline color styles',
    severity: 'warning',
  },
  {
    name: 'hardcoded-locale-path',
    check: /\]\(\/es\/|\]\(\/fi\//,
    message: 'Hardcoded non-English locale prefix in link path',
    suggestion: 'Use /en/library/... paths; es/fi content does not exist yet',
    severity: 'warning',
  },
  {
    name: 'empty-blockquote',
    check: (content) => {
      const lines = content.split('\n');
      for (let i = 0; i < lines.length; i++) {
        if (/^>\s*$/.test(lines[i])) {
          const prev = i > 0 ? lines[i - 1] : '';
          const next = i < lines.length - 1 ? lines[i + 1] : '';
          if (!prev.startsWith('>') && !next.startsWith('>')) {
            return true;
          }
        }
      }
      return false;
    },
    message:
      'Isolated empty blockquote line (not part of multi-line blockquote)',
    suggestion:
      'Remove orphaned > lines or connect them to adjacent blockquote content',
    severity: 'warning',
  },
  {
    name: 'missing-alt-text',
    check: /<Image[^>]*alt=["']["']/,
    message: 'Image component with empty alt text',
    suggestion: 'Provide descriptive alt text for accessibility',
    severity: 'warning',
  },
  {
    name: 'monster-sheet-missing-stat-table',
    check: (content, rel) =>
      rel.endsWith('.sheet.mdx') &&
      !content.match(/\|\s*\*{0,2}STR\*{0,2}\s*\|/),
    message: 'Monster sheet missing ability score table (| STR | DEX | ...)',
    suggestion: 'Add the standard 6-ability stat table',
    severity: 'critical',
    appliesTo: ['monsters'],
  },
  {
    name: 'monster-sheet-missing-cr',
    check: (content, rel) =>
      rel.endsWith('.sheet.mdx') && !content.match(/\*\*Challenge\*\*.*\d/),
    message: 'Monster sheet missing Challenge Rating line',
    suggestion: 'Add **Challenge**: X (Y XP) line',
    severity: 'warning',
    appliesTo: ['monsters'],
  },
  {
    name: 'spell-missing-blockquote-stat-block',
    check: (content) => !content.match(/^>\s+\*\*/m),
    message: 'Spell file missing blockquote stat block (> **Spell Name**)',
    suggestion:
      'Spell files should contain a blockquote (>) section with the spell stat block',
    severity: 'warning',
    appliesTo: ['spells'],
  },
];

/**
 * Determine the content type from a file path
 *
 * @param {string} relPath - Relative path from content root
 * @returns {string} Content type identifier
 */
function getContentType(relPath) {
  if (relPath.includes('monsters')) return 'monsters';
  if (relPath.includes('spells')) return 'spells';
  if (relPath.includes('items')) return 'items';
  if (relPath.includes('world')) return 'world';
  if (relPath.includes('rules')) return 'rules';
  if (relPath.includes('character-creation')) return 'character-creation';
  return 'other';
}

/**
 * Recursively find all MDX files
 *
 * @param {string} dir - Directory to scan
 * @param {string[]} results - Accumulator
 * @returns {Promise<string[]>} MDX file paths
 */
async function findMdxFiles(dir, results = []) {
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return results;
  }

  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory() && !entry.name.startsWith('.')) {
      await findMdxFiles(full, results);
    } else if (entry.name.endsWith('.mdx')) {
      results.push(full);
    }
  }
  return results;
}

/**
 * Run all applicable rules against a single file
 *
 * @param {string} absPath - Absolute file path
 * @param {string} content - File content
 * @param {string} relPath - Relative path from content root
 * @param {Set<string>} allComponents - All known component names
 * @returns {Object[]} Array of violation objects
 */
function checkFile(absPath, content, relPath, allComponents) {
  const contentType = getContentType(relPath);
  const violations = [];

  for (const rule of RULES) {
    if (rule.appliesTo && !rule.appliesTo.includes(contentType)) {
      continue;
    }

    let triggered = false;
    let detail = '';

    if (
      rule.check === '__dynamic__' &&
      rule.name === 'unregistered-component'
    ) {
      const componentRegex = /<([A-Z][A-Za-z]+)[\s/>]/g;
      let match;
      while ((match = componentRegex.exec(content)) !== null) {
        if (!allComponents.has(match[1])) {
          triggered = true;
          detail = `Unregistered component: <${match[1]}>`;
          break;
        }
      }
    } else if (typeof rule.check === 'function') {
      const result = rule.check(content, relPath);
      if (result && result !== false) {
        triggered = true;
        detail = typeof result === 'string' ? result : '';
      }
    } else if (rule.check instanceof RegExp) {
      triggered = rule.check.test(content);
    }

    if (triggered) {
      violations.push({
        file: relPath.replace(/\\/g, '/'),
        rule: rule.name,
        message: detail || rule.message,
        suggestion: rule.suggestion,
        severity: rule.severity,
      });
    }
  }

  return violations;
}

async function main() {
  const autoGenerated = await loadAutoGeneratedComponents();
  const allComponents = new Set([...REGISTERED_COMPONENTS, ...autoGenerated]);

  const files = await findMdxFiles(CONTENT_DIR);
  const allFailures = [];
  let criticalCount = 0;

  for (const absPath of files) {
    const content = await fs.readFile(absPath, 'utf-8');
    const relPath = path.relative(ROOT, absPath);
    const violations = checkFile(absPath, content, relPath, allComponents);

    for (const v of violations) {
      allFailures.push(v);
      if (v.severity === 'critical') {
        criticalCount++;
      }
    }
  }

  const hasCritical = criticalCount > 0;

  const result = {
    check: 'mdx-format',
    severity: hasCritical ? 'critical' : 'warning',
    passed: allFailures.length === 0,
    failures: allFailures,
    stats: {
      total_files_checked: files.length,
      violations_found: allFailures.length,
      critical_violations: criticalCount,
      warning_violations: allFailures.length - criticalCount,
    },
  };

  console.log(JSON.stringify(result, null, 2));
  process.exit(hasCritical ? 1 : 0);
}

main().catch((err) => {
  console.error('Fatal:', err.message);
  process.exit(1);
});
